"""Evaluate our include and actual Humble Nav2 conditions without starting processes."""
import importlib.util
import os
from pathlib import Path
from unittest.mock import patch
import yaml
import rclpy
from rclpy.node import Node as RosNode

from ament_index_python.packages import get_package_share_directory
from launch import LaunchContext, LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription, GroupAction, OpaqueFunction
from launch_ros.actions import SetRemap
from launch_ros.utilities import evaluate_parameters
from launch.launch_description_sources import PythonLaunchDescriptionSource


nav2_share = os.environ.get('GO2_NAV2_SHARE_DIR') or get_package_share_directory('nav2_bringup')
project = Path(__file__).resolve().parents[1]


def shares(package):
    # Only paths are supplied; substitutions and Nav2 conditions use real ROS launch.
    return nav2_share if package == 'nav2_bringup' else '/unused'


with patch('ament_index_python.packages.get_package_share_directory', side_effect=shares):
    spec = importlib.util.spec_from_file_location('go2_stack', project/'go2_3d/stack.launch.py')
    stack = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(stack)
    with patch.object(Path, 'read_text', return_value='<robot name="launch_test"/>'):
        description = stack.generate_launch_description()
    for mode in ('mapping', 'localization', 'navigation'):
        context = LaunchContext()
        context.launch_configurations['mode'] = mode
        for action in description.entities:
            if isinstance(action, DeclareLaunchArgument):
                action.execute(context)
        mapper_action = next(action for action in description.entities if isinstance(action, OpaqueFunction))
        for profile in ('standard', 'dense'):
            context.launch_configurations['gicp_params'] = str(
                project/'go2_3d'/('gicp_dense.yaml' if profile == 'dense' else 'gicp.yaml'))
            mapper = mapper_action.execute(context)[0]
            # Evaluate real ROS launch parameter substitutions and YAML order;
            # the override must be last, after the user's dense profile file.
            values = {}
            for value in evaluate_parameters(context, mapper._Node__parameters):
                if isinstance(value, Path):
                    values.update(yaml.safe_load(value.read_text())['go2_gicp']['ros__parameters'])
                else:
                    values.update(value)
            assert values['mode'] == ('mapping' if mode == 'mapping' else 'localization')
            expected_window = 0.5 if mode == 'mapping' and profile == 'dense' else 0.0
            assert values.get('scan_window', 0.0) == expected_window, (mode, profile, values)
            assert values['map_voxel_size'] == (0.02 if profile == 'dense' else 0.06)
            assert values['max_map_points'] == (1000000 if profile == 'dense' else 200000)
            assert values['localization_voxel_size'] == 0.05
            assert values['validity_timeout'] == 1.0
            # Check the actual named-node parameter files generated by
            # launch_ros. Wildcard CLI overrides can lose to named YAML;
            # inspecting merged Python dictionaries alone cannot catch it.
            mapper._perform_substitutions(context)
            arguments = ['--ros-args']
            generated = []
            for filename, is_file in mapper._Node__expanded_parameter_arguments:
                arguments += ['--params-file' if is_file else '-p', filename]
                if is_file and Path(filename).name.startswith('launch_params_'):
                    generated.append(Path(filename))
            rclpy.init(args=arguments)
            probe = RosNode('go2_gicp')
            try:
                for name in ('scan_window', 'map_voxel_size', 'validity_timeout'):
                    actual = probe.declare_parameter(name, 0.0).value
                    assert actual == values.get(name, 0.0), (mode, profile, name, actual)
            finally:
                probe.destroy_node()
                rclpy.shutdown()
                for path in generated:
                    path.unlink()
            print(f'PASS GICP launch: {mode}/{profile} scan_window={expected_window}; map density and acceptance deadline retained')
        group = next(action for action in description.entities if isinstance(action,GroupAction))
        assert group.condition.evaluate(context) == (mode == 'navigation')
        include = next(action for action in group.get_sub_entities()
                       if isinstance(action, IncludeLaunchDescription)
                       and isinstance(action.launch_description_source, PythonLaunchDescriptionSource))
        if mode == 'navigation':
            remap = next(action for action in group.get_sub_entities() if isinstance(action,SetRemap))
            remap.execute(context)
            assert ('goal_pose','/navigation/nav2_direct_goal_unused') in context.launch_configurations['ros_remaps']
            included = include.execute(context)
            for action in included:
                if not isinstance(action, LaunchDescription):
                    action.execute(context)
            nav2 = included[-1]
            for action in nav2.entities:
                if isinstance(action, DeclareLaunchArgument):
                    action.execute(context)
            conditions = [action.condition.evaluate(context) for action in nav2.entities
                          if getattr(action, 'condition', None) is not None]
            assert conditions == [True, False], conditions
            assert context.launch_configurations['use_composition'] == 'False'
            assert context.launch_configurations['autostart'] == 'false'
        print(f'PASS launch conditions: {mode}')
